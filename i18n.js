// Declare global current language variable
let currentLanguage = localStorage.getItem('language') || 'pt-BR';

// Translation function
function t(key) {
    if (!key) return '';
    return translations[currentLanguage]?.[key] || translations['pt-BR']?.[key] || key;
}

// Change language function
function changeLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);
    translatePage();
}

// Translate the entire page
function translatePage() {
    // Get current language for this session
    const lang = localStorage.getItem('language') || 'pt-BR';
    currentLanguage = lang;
    
    // Update HTML lang attribute
    document.documentElement.lang = lang;
    
    // Translate all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key) {
            // Only translate if no child elements also need translation
            if (!element.querySelector('[data-i18n]')) {
                element.textContent = t(key);
            }
        }
    });
    
    // Translate elements with data-i18n-html attribute
    document.querySelectorAll('[data-i18n-html]').forEach(element => {
        const key = element.getAttribute('data-i18n-html');
        if (key) {
            element.innerHTML = t(key);
        }
    });
    
    // Translate placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (key) {
            element.placeholder = t(key);
        }
    });
    
    // Translate title tag
    const titleElement = document.querySelector('title');
    if (titleElement && titleElement.hasAttribute('data-i18n')) {
        titleElement.textContent = t(titleElement.getAttribute('data-i18n'));
    }
}

// Initialize translations when DOM is ready
document.addEventListener('DOMContentLoaded', function() {
    translatePage();
});

// Export for use in other files
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { t, changeLanguage, translatePage, translations };
}
